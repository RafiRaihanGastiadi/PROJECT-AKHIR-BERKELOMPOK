    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    if (txtJudul.getText().trim().isEmpty() || txtPenulis.getText().trim().isEmpty() || txtTahun.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Semua data wajib diisi!");
        return;
    }
    
    try {
        Buku bk = new Buku(
            txtJudul.getText(),
            txtPenulis.getText(),
            cmbKategori.getSelectedItem().toString(),
            Integer.parseInt(txtTahun.getText()) 
        );
        
        String sql = "INSERT INTO buku (judul, penulis, kategori, tahun_terbit) VALUES (?, ?, ?, ?)";
        Connection conn = Koneksi.getConnection();
        PreparedStatement ps = conn.prepareStatement(sql);
        
        ps.setString(1, bk.getJudul());
        ps.setString(2, bk.getPenulis());
        ps.setString(3, bk.getKategori());
        ps.setInt(4, bk.getTahunTerbit());
        
        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Buku baru berhasil ditambahkan!");
        
        tampilData();
        bersihkanForm();
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Tahun terbit harus berupa angka tahun (contoh: 2024)!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSimpanActionPerformed

