    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
if (txtId.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Silakan pilih data buku pada tabel terlebih dahulu!");
        return;
    }
    
    try {
        Buku bk = new Buku(
            Integer.parseInt(txtId.getText()),
            txtJudul.getText(),
            txtPenulis.getText(),
            cmbKategori.getSelectedItem().toString(),
            Integer.parseInt(txtTahun.getText()) 
        );
        
        String sql = "UPDATE buku SET judul=?, penulis=?, kategori=?, tahun_terbit=? WHERE id=?";
        Connection conn = Koneksi.getConnection();
        PreparedStatement ps = conn.prepareStatement(sql);
        
        ps.setString(1, bk.getJudul());
        ps.setString(2, bk.getPenulis());
        ps.setString(3, bk.getKategori());
        ps.setInt(4, bk.getTahunTerbit());
        ps.setInt(5, bk.getId());
        
        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data buku berhasil diperbarui!");
        tampilData();
        bersihkanForm();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + e.getMessage());
    }       // TODO add your handling code here:
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Silakan pilih data buku yang ingin dihapus!");
            return;
        }
        
        int konfirmasi = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus buku ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                String sql = "DELETE FROM buku WHERE id=?";
                Connection conn = Koneksi.getConnection();
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setInt(1, Integer.parseInt(txtId.getText()));
                
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Buku berhasil dihapus dari sistem!");
                tampilData();
                bersihkanForm();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage());
            }
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

